import Foundation

public enum RejectionReason: String, Sendable {
    case concealed, excludedApplication, unknownSource, secureInput, sourceChanged
    case unsupported, tooLarge, empty, secret, selfWrite
}

public struct CaptureMetadata: Sendable {
    public var sourceBundleID: String?
    public var claimedSourceBundleID: String?
    public var types: Set<String>
    public var secureInput: Bool
    public var sourceChanged: Bool
    public var itemCount: Int

    public init(sourceBundleID: String?, claimedSourceBundleID: String? = nil,
                types: Set<String> = [], secureInput: Bool = false,
                sourceChanged: Bool = false, itemCount: Int = 1) {
        self.sourceBundleID = sourceBundleID
        self.claimedSourceBundleID = claimedSourceBundleID
        self.types = types
        self.secureInput = secureInput
        self.sourceChanged = sourceChanged
        self.itemCount = itemCount
    }
}

public struct CapturePolicy: Sendable {
    public static let maxTextBytes = 512 * 1_024
    public static let maxImageBytes = 4 * 1_024 * 1_024
    public static let maxFileBytes = 8 * 1_024 * 1_024
    public static let ownBundleID = "net.tagmat.copytaste"

    // Match bundle families as well as helper processes and browser extensions.
    public static let protectedBundlePrefixes: [String] = [
        "com.apple.passwords", "com.apple.keychainaccess", "com.apple.securityagent",
        "com.agilebits", "com.1password", "com.bitwarden", "com.8bit.bitwarden",
        "com.lastpass", "com.dashlane", "com.nordpass", "com.enpass", "in.sinew",
        "org.keepassxc", "com.keepass", "de.slpro", "com.mseven", "com.callpod.keeper",
        "com.keepersecurity", "com.roboform", "com.siber", "com.authy", "com.yubico"
    ]

    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "org.keepassxc.keepassxc", "net.tagmat.copytaste.private"
    ]

    public var excludedBundleIDs: Set<String>
    public init(excludedBundleIDs: Set<String> = []) {
        self.excludedBundleIDs = Set(excludedBundleIDs.map { $0.lowercased() })
    }

    public func isExcluded(_ bundleID: String) -> Bool {
        let identifier = bundleID.lowercased()
        return excludedBundleIDs.contains(identifier) || Self.protectedBundlePrefixes.contains {
            identifier == $0 || identifier.hasPrefix($0 + ".")
        }
    }

    // This gate must run before requesting text or image bytes from the pasteboard.
    public func rejection(for metadata: CaptureMetadata) -> RejectionReason? {
        if !metadata.types.isDisjoint(with: Self.privateTypes) { return .concealed }
        if metadata.secureInput { return .secureInput }
        if metadata.sourceChanged { return .sourceChanged }
        guard let source = metadata.sourceBundleID, !source.isEmpty else { return .unknownSource }
        if isExcluded(source) { return .excludedApplication }
        if let claimed = metadata.claimedSourceBundleID, isExcluded(claimed) { return .excludedApplication }
        if source == Self.ownBundleID || metadata.types.contains("net.tagmat.copytaste.origin") { return .selfWrite }
        if metadata.itemCount != 1 { return .unsupported }
        return nil
    }

    public static func isProtectedFileName(_ name: String) -> Bool {
        let lower = name.lowercased()
        let ext = (lower as NSString).pathExtension
        let protectedExtensions: Set<String> = ["pem", "key", "p12", "pfx", "kdbx", "keychain", "keychain-db", "mobileprovision", "provisionprofile", "keystore", "jks", "asc", "gpg"]
        return protectedExtensions.contains(ext) || ["password", "credential", "secret", "private_key", "recovery-key"].contains(where: lower.contains) || lower == ".env" || lower.hasPrefix(".env.") ||
            lower.hasPrefix("id_rsa") || lower.hasPrefix("id_ed25519") ||
            ["credentials", "credentials.json", "secrets.json", "secrets.yaml", "secrets.yml"].contains(lower)
    }

    public func rejection(forFile data: Data, name: String) -> RejectionReason? {
        if data.count > Self.maxFileBytes { return .tooLarge }
        if Self.isProtectedFileName(name) { return .secret }
        if Self.isTextFile(name) {
            guard let text = String(data: data, encoding: .utf8) else { return .unsupported }
            if !text.isEmpty { return rejection(forText: text) }
        }
        return nil
    }

    public static func isTextFile(_ name: String) -> Bool {
        let extensions: Set<String> = ["txt", "md", "markdown", "mdown", "csv", "tsv", "json", "yaml", "yml", "ini", "conf", "log", "xml", "html", "css", "swift", "js", "jsx", "ts", "tsx", "py", "sh", "rs", "go", "c", "cpp", "h", "java", "sql"]
        return extensions.contains((name as NSString).pathExtension.lowercased())
    }

    public func rejection(forText text: String) -> RejectionReason? {
        if text.utf8.count > Self.maxTextBytes { return .tooLarge }
        let value = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if value.isEmpty { return .empty }
        if Self.containsSecret(value) { return .secret }
        return nil
    }

    public static func kind(for text: String) -> ClipKind {
        guard !text.contains(where: \.isWhitespace), let url = URL(string: text),
              ["https", "http"].contains(url.scheme?.lowercased() ?? ""), url.host != nil else { return .text }
        return .link
    }

    private static func matches(_ pattern: String, _ text: String) -> Bool {
        text.range(of: pattern, options: .regularExpression) != nil
    }

    public static func containsSecret(_ text: String) -> Bool {
        let patterns = [
            #"-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY-----"#,
            #"(?i)\b(?:authorization["']?\s*:\s*["']?(?:bearer|basic)\s+|(?:password|passwd|pwd|secret|api[_-]?key|access[_-]?token|refresh[_-]?token|client[_-]?secret)["']?\s*[=:]\s*["']?)\S+"#,
            #"\b(?:gh[pousr]_[A-Za-z0-9_]{20,}|github_pat_[A-Za-z0-9_]{20,}|sk-[A-Za-z0-9_-]{20,}|AKIA[A-Z0-9]{16}|xox[baprs]-[A-Za-z0-9-]{15,})\b"#,
            #"\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\b"#,
            #"^\d{4,8}$"#
        ]
        if patterns.contains(where: { matches($0, text) }) { return true }
        if let components = URLComponents(string: text), components.scheme != nil {
            if components.password != nil || components.user != nil { return true }
            let secretKeys: Set<String> = ["token", "key", "password", "secret", "code", "auth", "apikey", "api_key", "access_token", "refresh_token", "client_secret", "signature", "sig"]
            if components.queryItems?.contains(where: { secretKeys.contains($0.name.lowercased()) }) == true { return true }
            if let fragment = components.fragment,
               matches(#"(?i)(?:token|password|secret|key|code)="#, fragment) { return true }
        }
        if containsPaymentNumber(text) { return true }
        // Conservative heuristic for isolated generated credentials. Prose is kept.
        if (12...256).contains(text.count), !text.contains(where: \.isWhitespace) {
            let classes = [text.rangeOfCharacter(from: .lowercaseLetters) != nil,
                           text.rangeOfCharacter(from: .uppercaseLetters) != nil,
                           text.rangeOfCharacter(from: .decimalDigits) != nil,
                           text.rangeOfCharacter(from: .punctuationCharacters.union(.symbols)) != nil]
            if classes.filter({ $0 }).count >= 3 && kind(for: text) != .link { return true }
        }
        return false
    }

    private static func containsPaymentNumber(_ text: String) -> Bool {
        guard let regex = try? NSRegularExpression(pattern: #"(?<!\d)(?:\d[ -]?){12,18}\d(?!\d)"#) else { return false }
        let ns = text as NSString
        return regex.matches(in: text, range: NSRange(location: 0, length: ns.length)).contains { match in
            let digits = ns.substring(with: match.range).compactMap(\.wholeNumberValue)
            guard (13...19).contains(digits.count), Set(digits).count > 1 else { return false }
            let total = digits.reversed().enumerated().reduce(0) { sum, pair in
                let n = pair.offset % 2 == 1 ? pair.element * 2 : pair.element
                return sum + (n > 9 ? n - 9 : n)
            }
            return total % 10 == 0
        }
    }
}
